 begin;

create table if not exists public.pelanggan (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  nama text not null check (length(btrim(nama)) > 0),
  no_hp text not null default '',
  alamat text not null default '',
  created_at timestamptz not null default now(),
  unique (id, user_id)
);

create table if not exists public.layanan (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  nama text not null check (length(btrim(nama)) > 0),
  harga numeric(12, 2) not null check (harga > 0),
  created_at timestamptz not null default now(),
  unique (id, user_id)
);

create table if not exists public.pesanan (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  pelanggan_id bigint not null,
  layanan_id bigint not null,
  berat numeric(8, 2) not null check (berat > 0),
  harga_per_kg numeric(12, 2) not null check (harga_per_kg > 0),
  status text not null default 'Diterima'
    check (status in ('Diterima', 'Dicuci', 'Selesai', 'Diambil')),
  total numeric(14, 0) generated always as (round(berat * harga_per_kg)) stored,
  tanggal_masuk date not null default current_date,
  tanggal_selesai date,
  created_at timestamptz not null default now(),
  foreign key (pelanggan_id, user_id)
    references public.pelanggan (id, user_id) on delete restrict,
  foreign key (layanan_id, user_id)
    references public.layanan (id, user_id) on delete restrict
);

create table if not exists public.pengaturan_publik (
  id boolean primary key default true check (id),
  owner_user_id uuid not null references auth.users (id) on delete cascade
);

create index if not exists pelanggan_user_id_idx on public.pelanggan (user_id);
create index if not exists layanan_user_id_idx on public.layanan (user_id);
create index if not exists pesanan_user_id_idx on public.pesanan (user_id);
create index if not exists pesanan_user_status_idx on public.pesanan (user_id, status);

create or replace view public.pesanan_publik
with (security_barrier = true, security_invoker = false)
as
select
  p.id,
  c.nama as pelanggan_nama,
  l.nama as layanan_nama,
  p.berat,
  p.status,
  p.total,
  p.tanggal_masuk
from public.pesanan as p
join public.pelanggan as c
  on c.id = p.pelanggan_id and c.user_id = p.user_id
join public.layanan as l
  on l.id = p.layanan_id and l.user_id = p.user_id
join public.pengaturan_publik as setting
  on setting.owner_user_id = p.user_id;

create or replace function public.set_data_pesanan()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  select l.harga
    into new.harga_per_kg
    from public.layanan as l
   where l.id = new.layanan_id
     and l.user_id = new.user_id;

  if new.harga_per_kg is null then
    raise exception 'Layanan tidak ditemukan untuk akun ini';
  end if;

  if new.status in ('Selesai', 'Diambil') then
    new.tanggal_selesai := coalesce(new.tanggal_selesai, current_date);
  else
    new.tanggal_selesai := null;
  end if;

  return new;
end;
$$;

drop trigger if exists pesanan_set_data on public.pesanan;
create trigger pesanan_set_data
before insert or update of layanan_id, status, tanggal_selesai
on public.pesanan
for each row execute function public.set_data_pesanan();

alter table public.pelanggan enable row level security;
alter table public.layanan enable row level security;
alter table public.pesanan enable row level security;
alter table public.pengaturan_publik enable row level security;

drop policy if exists "Pemilik mengelola pelanggan" on public.pelanggan;
create policy "Pemilik mengelola pelanggan"
  on public.pelanggan for all to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

drop policy if exists "Pemilik mengelola layanan" on public.layanan;
create policy "Pemilik mengelola layanan"
  on public.layanan for all to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

drop policy if exists "Pemilik mengelola pesanan" on public.pesanan;
create policy "Pemilik mengelola pesanan"
  on public.pesanan for all to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

revoke all on public.pelanggan, public.layanan, public.pesanan from anon;
grant select, insert, update, delete on public.pelanggan, public.layanan, public.pesanan to authenticated;
revoke all on sequence public.pelanggan_id_seq, public.layanan_id_seq, public.pesanan_id_seq from anon;
grant usage, select on sequence public.pelanggan_id_seq, public.layanan_id_seq, public.pesanan_id_seq to authenticated;
revoke all on public.pengaturan_publik from public, anon, authenticated;
revoke all on public.pesanan_publik from public, anon, authenticated;
grant select on public.pesanan_publik to anon, authenticated;

do $$
declare
  owner_id uuid;
begin
  select id
    into owner_id
    from auth.users
   where lower(email) = lower('OWNER_EMAIL');

  if owner_id is null then
    raise exception 'Ganti OWNER_EMAIL dengan email akun Supabase yang sudah ada di Authentication > Users.';
  end if;

  insert into public.pengaturan_publik (id, owner_user_id)
  values (true, owner_id)
  on conflict (id) do update
    set owner_user_id = excluded.owner_user_id;

  insert into public.pelanggan (user_id, nama, no_hp, alamat)
  select owner_id, sample.nama, sample.no_hp, sample.alamat
    from (values
      ('Siti Rahmawati', '081234567890', 'Gatak, Sukoharjo'),
      ('Budi Santoso', '082233445566', 'Kartasura, Sukoharjo'),
      ('Dewi Lestari', '085611223344', 'Laweyan, Surakarta')
    ) as sample(nama, no_hp, alamat)
   where not exists (
     select 1 from public.pelanggan as p
      where p.user_id = owner_id and p.nama = sample.nama
   );

  insert into public.layanan (user_id, nama, harga)
  select owner_id, sample.nama, sample.harga
    from (values
      ('Cuci kiloan', 6000::numeric),
      ('Cuci dan setrika', 8000::numeric),
      ('Setrika saja', 4000::numeric)
    ) as sample(nama, harga)
   where not exists (
     select 1 from public.layanan as l
      where l.user_id = owner_id and l.nama = sample.nama
   );

  insert into public.pesanan
    (user_id, pelanggan_id, layanan_id, berat, status, tanggal_masuk, tanggal_selesai)
  select owner_id, customer.id, service.id, sample.berat, sample.status,
         sample.tanggal_masuk, sample.tanggal_selesai
    from (values
      ('Siti Rahmawati', 'Cuci dan setrika', 3.5::numeric, 'Dicuci', date '2026-11-16', null::date),
      ('Budi Santoso', 'Cuci kiloan', 5.0::numeric, 'Dicuci', date '2026-11-15', null::date),
      ('Dewi Lestari', 'Setrika saja', 2.0::numeric, 'Selesai', date '2026-11-14', date '2026-11-16'),
      ('Siti Rahmawati', 'Cuci kiloan', 4.0::numeric, 'Diambil', date '2026-11-12', date '2026-11-13')
    ) as sample(nama_pelanggan, nama_layanan, berat, status, tanggal_masuk, tanggal_selesai)
    join lateral (
      select p.id from public.pelanggan as p
       where p.user_id = owner_id and p.nama = sample.nama_pelanggan
       order by p.id limit 1
    ) as customer on true
    join lateral (
      select l.id from public.layanan as l
       where l.user_id = owner_id and l.nama = sample.nama_layanan
       order by l.id limit 1
    ) as service on true
   where not exists (
     select 1 from public.pesanan as existing
      where existing.user_id = owner_id
        and existing.pelanggan_id = customer.id
        and existing.layanan_id = service.id
        and existing.berat = sample.berat
        and existing.tanggal_masuk = sample.tanggal_masuk
   );
end;
$$;

notify pgrst, 'reload schema';
commit;
