  on public.layanan for all to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

create policy "Pemilik mengelola pesanan"
  on public.pesanan for all to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

